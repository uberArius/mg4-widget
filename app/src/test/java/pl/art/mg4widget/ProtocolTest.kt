package pl.art.mg4widget

import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test
import okhttp3.mockwebserver.MockResponse
import okhttp3.mockwebserver.MockWebServer
import java.util.Base64

class ProtocolTest {
    @Test fun `email login omits country code and preserves password hashing`() {
        MockWebServer().use { server ->
            server.enqueue(MockResponse().setBody("""{"code":0,"data":{"access_token":"test-token","expires_in":3600}}"""))
            SaicApi(base = server.url("/api").toString()).login("test@example.invalid", " example-password ", "48")
            val req = server.takeRequest()
            val date = req.getHeader("APP-SEND-DATE")!!
            val type = req.getHeader("ORIGINAL-CONTENT-TYPE")!!
            val key = SaicCrypto.md5(SaicCrypto.md5("/oauth/token459771app") + date + "1" + type)
            val plain = SaicCrypto.aes(req.body.readUtf8(), key, SaicCrypto.md5(date), true)
            val form = plain.split('&').associate {
                val parts = it.split('=', limit = 2)
                parts[0] to java.net.URLDecoder.decode(parts[1], "UTF-8")
            }
            assertEquals("2", form["loginType"])
            assertEquals("test@example.invalid", form["username"])
            assertFalse(form.containsKey("countryCode"))
            assertEquals(SaicCrypto.hash("SHA-1", " example-password "), form["password"])
        }
    }
    @Test fun `unknown login error preserves server description without retry`() {
        MockWebServer().use { server ->
            server.enqueue(MockResponse().setBody("""{"code":15030,"message":"Synthetic server explanation"}"""))
            try {
                SaicApi(base = server.url("/api").toString()).login("test@example.invalid", "test-password", "48")
                fail("Expected API failure")
            } catch (e: ApiFailure) {
                assertEquals(15030, e.code)
                assertTrue(e.message!!.contains("Synthetic server explanation"))
            }
            assertEquals(1, server.requestCount)
        }
    }
    private fun vectors() = JSONObject(javaClass.getResource("/crypto-vectors.json")!!.readText())
    @Test fun `request encryption matches original Python client including query string`() {
        val cases = vectors().getJSONArray("requests")
        repeat(cases.length()) {
            val v = cases.getJSONObject(it)
            val actual = SaicCrypto.encrypt(v.getString("path"), v.getString("timestamp"), v.getString("type"), v.getString("body"), v.getString("token"))
            assertEquals(v.getString("encrypted"), actual.body)
            assertEquals(v.getString("signature"), actual.signature)
        }
    }
    @Test fun `decrypts server response generated by upstream`() {
        val v = vectors().getJSONObject("response")
        assertEquals(v.getString("plain"), SaicCrypto.decrypt(v.getString("encrypted"), v.getString("timestamp"), v.getString("type")))
    }
    @Test fun `asynchronous request reuses event id instead of restarting command`() {
        MockWebServer().use { server ->
            server.enqueue(MockResponse().setBody("""{"code":0}""").addHeader("event-id", "event-123"))
            server.enqueue(MockResponse().setBody("""{"code":0,"data":{"ok":true}}"""))
            val api = SaicApi(base = server.url("/api").toString(), sleep = {})
            assertTrue(api.request("/vehicle/control", "POST", "{}", event = true).getBoolean("ok"))
            assertEquals("0", server.takeRequest().getHeader("event-id"))
            assertEquals("event-123", server.takeRequest().getHeader("event-id"))
        }
    }
    @Test fun `lost session does not retry login or control`() {
        MockWebServer().use { server ->
            server.enqueue(MockResponse().setResponseCode(401))
            try { SaicApi(base = server.url("/api").toString(), sleep = {}).request("/vehicle/control", "POST", "{}", event = true); fail() }
            catch (e: ApiFailure) { assertEquals(401, e.code) }
            assertEquals(1, server.requestCount)
        }
    }
    @Test fun `MG4 temperature and stop payload follow upstream`() {
        val start = SaicApi.climateBody("test-vin", 22, true)
        assertEquals(SaicCrypto.hash("SHA-256", "test-vin"), start.getString("vin"))
        val params = start.getJSONArray("rvcParams")
        assertEquals(20, params.getJSONObject(1).getInt("paramId"))
        assertArrayEquals(byteArrayOf(8), Base64.getDecoder().decode(params.getJSONObject(1).getString("paramValue")))
        val stop = SaicApi.climateBody("test-vin", 22, false).getJSONArray("rvcParams")
        assertEquals(22, stop.getJSONObject(1).getInt("paramId"))
        assertEquals(255, stop.getJSONObject(2).getInt("paramId"))
    }
}
